"""Per-origin State-minus-flat Winkler difference over test time (plan.md Phase 6).

Reads the stored confirmatory runs only; it scores nothing new.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from paired_interval_inference import _cell_delta, _load_cell_runs  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results_root", type=Path, default=ROOT / "results" / "publication")
    parser.add_argument("--horizon", type=int, default=336)
    parser.add_argument("--figure-dir", type=Path, default=ROOT / "manuscript" / "figures")
    parser.add_argument("--generated-dir", type=Path, default=ROOT / "manuscript" / "generated")
    args = parser.parse_args()
    cells = _load_cell_runs(args.results_root, {"ECL", "solar"})
    macros = []
    fig, axes = plt.subplots(1, 2, figsize=(8, 2.6))
    for ax, data in zip(axes, ("ECL", "solar")):
        runs = cells[(data, args.horizon)]
        delta, flat_mean = _cell_delta(runs)
        relative = 100 * delta / flat_mean
        # Thirds of the test split in time order, as a plain summary of drift over the test period.
        for name, part in zip(("One", "Two", "Three"), np.array_split(relative, 3)):
            macros.append(rf"\newcommand{{\Origin{'Ecl' if data == 'ECL' else 'Solar'}Third{name}}}{{{part.mean():+.2f}}}")
        # Same block length as the prespecified bootstrap, so the smoothing matches its dependence span.
        block = math.ceil(args.horizon / runs[0]["stride"])
        smooth = np.convolve(relative, np.ones(block) / block, mode="valid")
        origins = runs[0]["origins"]
        ax.plot(origins, relative, ".", ms=2, color="#999999")
        ax.plot(origins[block - 1:], smooth, color="#0072b2", lw=1.2)
        ax.axhline(0, color="#555555", lw=0.7)
        ax.axhline(relative.mean(), color="#d55e00", lw=0.8, ls="--")
        ax.set(title=f"{'Solar' if data == 'solar' else data}, H={args.horizon}", xlabel="Test origin index",
               ylabel="Cluster − flat (%)")
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    args.figure_dir.mkdir(parents=True, exist_ok=True)
    for suffix in ("pdf", "png"):
        fig.savefig(args.figure_dir / f"origin_difference.{suffix}", dpi=180, bbox_inches="tight")
    args.generated_dir.mkdir(parents=True, exist_ok=True)
    (args.generated_dir / "origin_numbers.tex").write_text(
        "% Generated by manuscript/analysis/plot_origin_difference.py. Do not edit.\n" + "\n".join(macros) + "\n",
        encoding="utf-8")
    print(f"Wrote {args.figure_dir / 'origin_difference.pdf'} and {args.generated_dir / 'origin_numbers.tex'}")


if __name__ == "__main__":
    main()
